-- Credit Cards / Loans: standalone accounts with their own purchases, paid down by the user's credits.
--
-- Like 001_debt_paydown.sql, these tables are created by hand: the fpfl schema is owned by API-JDK
-- (Hibernate ddl-auto: update), which leaves tables it doesn't know about alone, and API-NET never runs
-- EF migrations. Purely additive and safe to run more than once.
--
--   psql "host=localhost dbname=FPFL-V3 user=postgres" -f db/002_credit_accounts.sql
--
-- * A purchase raises the account's balance; it never touches the main bank forecast.
-- * A payment links one of the user's credits (fpfl.items, type 1) to the account: each occurrence of the
--   credit sends either a fixed amount or a percentage of it. That money leaves the bank forecast and
--   lowers the account's balance.
-- Deleting an account removes its purchases and payments; deleting a credit removes its payments.

CREATE TABLE IF NOT EXISTS fpfl.credit_accounts (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          uuid          NOT NULL,
    name             varchar(150)  NOT NULL,
    kind             varchar(20)   NOT NULL CHECK (kind IN ('CreditCard', 'Loan')),
    opening_balance  numeric(14,2) NOT NULL CHECK (opening_balance >= 0),
    balance_date     date          NOT NULL,
    apr              numeric(6,3)  NOT NULL DEFAULT 0 CHECK (apr >= 0 AND apr <= 100),
    credit_limit     numeric(14,2)     NULL CHECK (credit_limit IS NULL OR credit_limit > 0),
    created_at       timestamptz   NOT NULL DEFAULT now(),
    UNIQUE (user_id, name)
);

CREATE INDEX IF NOT EXISTS ix_credit_accounts_user_id ON fpfl.credit_accounts (user_id);

-- Purchases support One Time (1), Daily (2) and Weekly (3) for now; the columns match fpfl.items.
CREATE TABLE IF NOT EXISTS fpfl.account_purchases (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_account       bigint        NOT NULL REFERENCES fpfl.credit_accounts (id) ON DELETE CASCADE,
    name             varchar(150)  NOT NULL,
    amount           numeric(14,2) NOT NULL CHECK (amount > 0),
    fk_time_period   bigint        NOT NULL REFERENCES fpfl.time_periods (id) CHECK (fk_time_period IN (1, 2, 3)),
    begin_date       date              NULL,
    end_date         date              NULL,
    weekly_dow       integer           NULL CHECK (weekly_dow IS NULL OR weekly_dow BETWEEN 0 AND 6),
    date_range_req   boolean       NOT NULL DEFAULT false,
    created_at       timestamptz   NOT NULL DEFAULT now(),
    CHECK (begin_date IS NULL OR end_date IS NULL OR begin_date <= end_date)
);

CREATE INDEX IF NOT EXISTS ix_account_purchases_account ON fpfl.account_purchases (fk_account);

-- Exactly one of amount / percent is set.
CREATE TABLE IF NOT EXISTS fpfl.account_payments (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_account       bigint        NOT NULL REFERENCES fpfl.credit_accounts (id) ON DELETE CASCADE,
    fk_credit_item   bigint        NOT NULL REFERENCES fpfl.items (id) ON DELETE CASCADE,
    amount           numeric(14,2)     NULL CHECK (amount IS NULL OR amount > 0),
    percent          numeric(5,2)      NULL CHECK (percent IS NULL OR (percent > 0 AND percent <= 100)),
    CHECK ((amount IS NULL) <> (percent IS NULL)),
    UNIQUE (fk_account, fk_credit_item)
);

CREATE INDEX IF NOT EXISTS ix_account_payments_credit ON fpfl.account_payments (fk_credit_item);
